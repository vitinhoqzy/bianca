create table if not exists public.declarations (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(trim(nickname)) between 1 and 40),
  message text not null check (char_length(trim(message)) between 1 and 1000),
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_scores (
  id bigint generated by default as identity primary key,
  nickname text not null check (char_length(trim(nickname)) between 1 and 40),
  score integer not null check (score in (0, 25, 50, 75, 100)),
  correct_answers integer not null check (correct_answers between 0 and 10),
  created_at timestamptz not null default now()
);

-- Provas de conclusão do quiz: cada uma pode autorizar somente uma declaração.
create table if not exists public.quiz_completion_tokens (
  id uuid primary key,
  nickname text not null check (char_length(trim(nickname)) between 1 and 40),
  expires_at timestamptz not null,
  used_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.declarations enable row level security;
alter table public.quiz_scores enable row level security;
alter table public.quiz_completion_tokens enable row level security;

grant select on public.declarations to authenticated;
grant select on public.quiz_scores to authenticated;
