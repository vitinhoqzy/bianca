-- Consumir a prova e criar a declaração na mesma transação evita reutilização.
create or replace function public.submit_declaration_once(
  p_nonce uuid,
  p_expires_at timestamptz,
  p_nickname text,
  p_message text
)
returns boolean
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
begin
  if char_length(trim(p_nickname)) not between 1 and 40
     or char_length(trim(p_message)) not between 1 and 1000 then
    return false;
  end if;

  update public.quiz_completion_tokens
  set used_at = now()
  where id = p_nonce
    and nickname = p_nickname
    and expires_at = p_expires_at
    and expires_at > now()
    and used_at is null;

  if not found then
    return false;
  end if;

  insert into public.declarations (nickname, message)
  values (trim(p_nickname), trim(p_message));

  return true;
end;
$$;

revoke all on function public.submit_declaration_once(uuid, timestamptz, text, text) from public, anon, authenticated;
grant execute on function public.submit_declaration_once(uuid, timestamptz, text, text) to service_role;
